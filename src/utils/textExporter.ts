import { QuadraticResult } from "./quadraticSolver";
import { Language } from "../i18n/translations";

export function formatSolutionToPlainText(result: QuadraticResult, lang: Language = "en"): string {
  const lines: string[] = [];

  const headers = {
    en: {
      title: "【Quadratic Equation Solution Report】",
      eq: "Equation",
      coeffs: "Coefficients",
      section1: "I. Discriminant & Root Nature",
      section2: "II. Vieta's Relations (Roots and Coefficients)",
      sum: "Sum of Roots: x₁ + x₂ = -b/a =",
      prod: "Product of Roots: x₁ · x₂ = c/a =",
      section3: "III. Completing the Square Step-by-Step Procedure",
      step: "Step",
      desc: "Explanation",
      math: "Expression",
      section4: "IV. Key Symmetric Polynomial Results",
      footer: "—— Generated by Vieta's Formulas & Quadratic Solver ——",
    },
    es: {
      title: "【Informe de Resolución de la Ecuación Cuadrática】",
      eq: "Ecuación",
      coeffs: "Coeficientes",
      section1: "I. Discriminante y Naturaleza de las Raíces",
      section2: "II. Relaciones de Vieta (Raíces y Coeficientes)",
      sum: "Suma de Raíces: x₁ + x₂ = -b/a =",
      prod: "Producto de Raíces: x₁ · x₂ = c/a =",
      section3: "III. Procedimiento Detallado de Completar el Cuadrado",
      step: "Paso",
      desc: "Descripción",
      math: "Cálculo",
      section4: "IV. Resultados de Polinomios Simétricos",
      footer: "—— Generado por Calculadora del Teorema de Vieta ——",
    },
    fr: {
      title: "【Rapport de Résolution de l'Équation du Second Degré】",
      eq: "Équation",
      coeffs: "Coefficients",
      section1: "I. Discriminant et Nature des Racines",
      section2: "II. Relations de Viète (Somme et Produit)",
      sum: "Somme des Racines : x₁ + x₂ = -b/a =",
      prod: "Produit des Racines : x₁ · x₂ = c/a =",
      section3: "III. Démarche Détaillée de Complétion du Carré",
      step: "Étape",
      desc: "Explication",
      math: "Formule",
      section4: "IV. Valeurs des Polynômes Symétriques",
      footer: "—— Généré par le Calculateur des Formules de Viète ——",
    },
    pt: {
      title: "【Relatório de Resolução da Equação do 2º Grau】",
      eq: "Equação",
      coeffs: "Coeficientes",
      section1: "I. Discriminante e Natureza das Raízes",
      section2: "II. Relações de Girard / Vieta",
      sum: "Suma das Raízes: x₁ + x₂ = -b/a =",
      prod: "Produto das Raízes: x₁ · x₂ = c/a =",
      section3: "III. Método de Completar Quadrados Passo a Passo",
      step: "Passo",
      desc: "Explicação",
      math: "Cálculo",
      section4: "IV. Polinômios Simétricos Fundamentais",
      footer: "—— Gerado pela Calculadora de Fórmulas de Vieta / Girard ——",
    },
    zh: {
      title: "【一元二次方程求解报告】",
      eq: "方程",
      coeffs: "系数",
      section1: "一、根的判别式与根的性质",
      section2: "二、韦达定理（根与系数关系）",
      sum: "两根之和：x₁ + x₂ = -b/a =",
      prod: "两根之积：x₁ · x₂ = c/a =",
      section3: "三、配方法详细解题五步过程",
      step: "步骤",
      desc: "说明",
      math: "算式",
      section4: "四、核心对称代数式结果",
      footer: "—— 由 韦达定理根与系数计算器 自动生成 ——",
    },
  }[lang] || {
    title: "【Quadratic Equation Solution Report】",
    eq: "Equation",
    coeffs: "Coefficients",
    section1: "I. Discriminant & Root Nature",
    section2: "II. Vieta's Relations (Roots and Coefficients)",
    sum: "Sum of Roots: x₁ + x₂ = -b/a =",
    prod: "Product of Roots: x₁ · x₂ = c/a =",
    section3: "III. Completing the Square Step-by-Step Procedure",
    step: "Step",
    desc: "Explanation",
    math: "Expression",
    section4: "IV. Key Symmetric Polynomial Results",
    footer: "—— Generated by Vieta's Formulas & Quadratic Solver ——",
  };

  const cleanTex = (s: string) =>
    s
      .replace(/\\frac\{([^}]+)\}\{([^}]+)\}/g, "$1/$2")
      .replace(/\\left|\\right/g, "")
      .replace(/\\pm/g, "±")
      .replace(/\\sqrt\{([^}]+)\}/g, "√($1)")
      .replace(/\\Delta/g, "Δ")
      .replace(/\\text\{([^}]+)\}/g, "$1")
      .replace(/\\cdot/g, "·")
      .replace(/\\quad/g, " ");

  lines.push(headers.title);
  lines.push(`${headers.eq}: ${cleanTex(result.standardEquationTex)}`);
  lines.push(`${headers.coeffs}: a = ${result.a.toString()}, b = ${result.b.toString()}, c = ${result.c.toString()}`);
  lines.push("");
  lines.push(headers.section1);
  lines.push(`Δ = b² - 4ac = (${result.b.toString()})² - 4 × (${result.a.toString()}) × (${result.c.toString()}) = ${result.delta.toString()}`);
  lines.push(`${cleanTex(result.deltaExplanation)}`);
  lines.push(`Roots: ${cleanTex(result.roots.exactTex1)}, ${cleanTex(result.roots.exactTex2)}`);
  lines.push("");
  lines.push(headers.section2);
  lines.push(`${headers.sum} ${result.sumOfRoots.toString()}`);
  lines.push(`${headers.prod} ${result.productOfRoots.toString()}`);
  lines.push("");
  lines.push(headers.section3);
  result.completingSquareSteps.forEach((st) => {
    lines.push(`${headers.step} ${st.stepIndex}【${st.title}】：`);
    lines.push(`  ${headers.desc}: ${st.description}`);
    lines.push(`  ${headers.math}: ${cleanTex(st.mathTex)}`);
  });
  lines.push("");
  lines.push(headers.section4);
  result.symmetricExpressions.slice(0, 5).forEach((item) => {
    lines.push(`• ${item.name} (${cleanTex(item.formulaTex)}): = ${cleanTex(item.resultTex)}`);
  });
  lines.push("");
  lines.push(headers.footer);

  return lines.join("\n");
}
